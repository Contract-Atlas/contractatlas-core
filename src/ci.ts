#!/usr/bin/env node
import { realpathSync } from "node:fs";
import { appendFile, mkdir, readFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { runCli, type CliIo } from "./cli.ts";
import { parseReport } from "./reportSchema.ts";

export interface CiOptions {
  manifest: string;
  rpc: string;
  /** Default strict policy fails drift, incomplete and unavailable. */
  strict?: boolean;
  directory: string;
  outputFile?: string;
  summaryFile?: string;
  /** Local fake-RPC tests only. The public action always requires HTTPS. */
  allowHttp?: boolean;
}

/** Shared by the GitHub Action and fake-RPC integration tests. Never writes to a network. */
export async function runCi(options: CiOptions, io: CliIo): Promise<number> {
  await mkdir(options.directory, { recursive: true });
  const reportPath = resolve(options.directory, "report.json");
  const badgePath = resolve(options.directory, "badge.svg");
  const args = ["check", resolve(options.manifest), "--rpc", options.rpc, "--format", "json", "--out", reportPath, "--badge-out", badgePath];
  if (options.strict !== false) args.push("--strict");
  if (options.allowHttp) args.push("--allow-http");
  const exit = await runCli(args, io);
  // Invalid input and unexpected failures must not reuse output from an older run.
  if (exit > 1) return exit;
  const parsed = parseReport(JSON.parse(await readFile(reportPath, "utf8")));
  if (!parsed.ok) throw new Error(`Checker produced an invalid report: ${parsed.error}`);
  const report = parsed.report;
  if (options.outputFile) {
    // Paths here are generated by us in RUNNER_TEMP; user inputs never become workflow commands.
    await appendFile(options.outputFile, `report=${reportPath}\nbadge=${badgePath}\noverall=${report.overall}\nexit-code=${exit}\n`);
  }
  if (options.summaryFile) {
    const counts = report.summary;
    await appendFile(options.summaryFile, `## ContractAtlas observation\n\nOverall: **${report.overall}**. Match: ${counts.match}; drift: ${counts.drift}; incomplete: ${counts.incomplete}; unavailable: ${counts.unavailable}.\n\nThis is a point-in-time hash observation, not an audit or endorsement. Download the report artifact for evidence and limitations.\n`);
  }
  return exit;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  const strict = process.env.CONTRACTATLAS_STRICT ?? "true";
  if (strict !== "true" && strict !== "false") throw new Error("strict must be true or false");
  const manifest = process.env.CONTRACTATLAS_MANIFEST;
  const rpc = process.env.CONTRACTATLAS_RPC;
  if (!manifest || !rpc || !process.env.RUNNER_TEMP) throw new Error("manifest, rpc and RUNNER_TEMP are required");
  runCi({
    manifest,
    rpc,
    strict: strict === "true",
    directory: join(process.env.RUNNER_TEMP, `contractatlas-${process.env.GITHUB_ACTION ?? "check"}`),
    outputFile: process.env.GITHUB_OUTPUT,
    summaryFile: process.env.GITHUB_STEP_SUMMARY,
  }, { stdout: (s) => process.stdout.write(s), stderr: (s) => process.stderr.write(s) })
    .then((code) => { process.exitCode = code; })
    .catch((error: unknown) => { console.error(error instanceof Error ? error.message : String(error)); process.exitCode = 3; });
}
